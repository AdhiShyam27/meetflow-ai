// ── HTML helpers ──────────────────────────────────────────────────────────────

export function esc(str: string): string {
  return str
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");
}

// ── Email template builder ────────────────────────────────────────────────────

export function buildSummaryEmailHtml(meeting: {
  title: string;
  created_at?: string;
  platform?: string;
  duration?: number;
  summary: {
    overview?: string;
    keyPoints?: string[];
    actionItems?: Array<{ task: string; owner?: string | null; dueDate?: string | null }>;
    decisions?: string[];
    questions?: string[];
  } | null;
}): string {
  const s = meeting.summary ?? {};
  const sections: string[] = [];

  if (s.overview) {
    sections.push(
      `<h2 style="color:#4F46E5;font-size:16px;margin:20px 0 8px">Overview</h2>` +
      `<p style="color:#374151;line-height:1.6">${esc(s.overview)}</p>`
    );
  }
  if (s.keyPoints?.length) {
    sections.push(
      `<h2 style="color:#4F46E5;font-size:16px;margin:20px 0 8px">Key Points</h2>` +
      `<ul style="color:#374151;padding-left:20px">` +
      s.keyPoints.map((k) => `<li style="margin-bottom:6px">${esc(k)}</li>`).join("") +
      `</ul>`
    );
  }
  if (s.actionItems?.length) {
    sections.push(
      `<h2 style="color:#4F46E5;font-size:16px;margin:20px 0 8px">&#9989; Action Items</h2>` +
      `<ul style="color:#374151;padding-left:20px">` +
      s.actionItems
        .map(
          (a) =>
            `<li style="margin-bottom:6px">` +
            `<input type="checkbox" disabled style="margin-right:6px" />` +
            `<strong>${esc(a.task)}</strong>` +
            (a.owner ? ` &mdash; ${esc(a.owner)}` : "") +
            (a.dueDate ? ` <em>(${esc(a.dueDate)})</em>` : "") +
            `</li>`
        )
        .join("") +
      `</ul>`
    );
  }
  if (s.decisions?.length) {
    sections.push(
      `<h2 style="color:#14B8A6;font-size:16px;margin:20px 0 8px">&#128278; Decisions</h2>` +
      `<ul style="color:#374151;padding-left:20px">` +
      s.decisions.map((d) => `<li style="margin-bottom:6px">${esc(d)}</li>`).join("") +
      `</ul>`
    );
  }
  if (s.questions?.length) {
    sections.push(
      `<h2 style="color:#F59E0B;font-size:16px;margin:20px 0 8px">&#10067; Open Questions</h2>` +
      `<ul style="color:#374151;padding-left:20px">` +
      s.questions.map((q) => `<li style="margin-bottom:6px">${esc(q)}</li>`).join("") +
      `</ul>`
    );
  }

  const meta: string[] = [];
  if (meeting.platform) meta.push(`Platform: ${esc(meeting.platform.replace("_", " "))}`);
  if (meeting.duration) meta.push(`Duration: ${Math.floor(meeting.duration / 60)}m`);
  if (meeting.created_at) meta.push(new Date(meeting.created_at).toLocaleDateString());

  return (
    `<!DOCTYPE html><html><body style="font-family:'Segoe UI',sans-serif;max-width:600px;margin:0 auto;padding:24px">` +
    `<div style="background:linear-gradient(135deg,#4F46E5,#14B8A6);padding:24px;border-radius:12px;margin-bottom:24px">` +
    `<h1 style="color:white;margin:0;font-size:22px">&#128203; Meeting Summary</h1>` +
    `<p style="color:rgba(255,255,255,0.85);margin:6px 0 0;font-size:14px">${esc(meeting.title)}</p>` +
    (meta.length ? `<p style="color:rgba(255,255,255,0.65);margin:4px 0 0;font-size:12px">${meta.join(" &middot; ")}</p>` : "") +
    `</div>` +
    sections.join("") +
    `<hr style="border:none;border-top:1px solid #E5E7EB;margin:28px 0">` +
    `<p style="color:#9CA3AF;font-size:12px;text-align:center">Generated by <strong>MeetFlow AI</strong></p>` +
    `</body></html>`
  );
}

// ── MIME message builder ──────────────────────────────────────────────────────

export function buildMimeMessage(
  to: string,
  subject: string,
  html: string,
  bcc?: string
): string {
  const lines = [
    `To: ${to}`,
    `Subject: ${subject}`,
    "Content-Type: text/html; charset=utf-8",
    "MIME-Version: 1.0",
  ];
  if (bcc) lines.push(`Bcc: ${bcc}`);
  lines.push("", html);
  return Buffer.from(lines.join("\r\n")).toString("base64url");
}

// ── Gmail send ────────────────────────────────────────────────────────────────

/**
 * Send a single HTML email via the Gmail API.
 * Throws on failure.
 */
export async function sendGmailMessage(
  accessToken: string,
  to: string,
  subject: string,
  htmlBody: string,
  bcc?: string
): Promise<void> {
  const raw = buildMimeMessage(to, subject, htmlBody, bcc);
  const res = await fetch("https://gmail.googleapis.com/gmail/v1/users/me/messages/send", {
    method: "POST",
    headers: {
      Authorization: `Bearer ${accessToken}`,
      "Content-Type": "application/json",
    },
    body: JSON.stringify({ raw }),
    signal: AbortSignal.timeout(15_000),
  });

  if (!res.ok) {
    const err = await res.json().catch(() => ({})) as { error?: { message?: string } };
    throw new Error(err.error?.message ?? `Gmail send failed: ${res.status}`);
  }
}
